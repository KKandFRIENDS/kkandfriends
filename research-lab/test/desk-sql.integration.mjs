// Run with PGLITE_MODULE pointing to an installed @electric-sql/pglite dist/index.js.
// Runs the real migration and transactions in an isolated PostgreSQL WASM engine.
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const { PGlite } = await import(pathToFileURL(process.env.PGLITE_MODULE).href);
const db = new PGlite();
await db.exec('create role anon; create role authenticated; create role service_role;');
await db.exec(await readFile(new URL('../../db/migrations/015_editorial_desk.sql', import.meta.url), 'utf8'));
await db.exec(await readFile(new URL('../../db/migrations/016_editorial_stage_lease.sql', import.meta.url), 'utf8'));
const attempt = '11111111-1111-4111-8111-111111111111';
const other = '22222222-2222-4222-8222-222222222222';
const date = '2026-09-07', id = `${date}-macro`;
const query = (sql,args=[])=>db.query(sql,args);
assert.equal((await query('select editorial_claim($1,$2) as ok',[date,attempt])).rows[0].ok,true);
assert.equal((await query('select editorial_claim($1,$2) as ok',[date,other])).rows[0].ok,false);
assert.equal((await query('select editorial_renew($1,$2) as ok',[date,attempt])).rows[0].ok,true);
assert.equal((await query('select editorial_renew($1,$2) as ok',[date,other])).rows[0].ok,false);
const payload={desk:{id:'macro'},content:{title:'original'}};
await assert.rejects(query('select editorial_finish($1,$2,$3,$4,$5)',[date,other,payload,'h1',{}]),/Lost run lease/);
await query('select editorial_finish($1,$2,$3,$4,$5)',[date,attempt,payload,'h1',{}]);
const transition=(version,action,p=payload,hash='h1',reviewed=true)=>query('select editorial_transition($1,$2,$3,$4,$5,$6)',[id,version,action,p,hash,reviewed]);
await assert.rejects(transition(1,'publish'),/Approval mismatch/);
await assert.rejects(transition(1,'approve',payload,'h1',false),/Review required/);
await transition(1,'approve');
await assert.rejects(transition(1,'publish'),/Stale draft/);
await transition(2,'revise',{...payload,content:{title:'revised'}},'h2');
await assert.rejects(transition(3,'publish',payload,'h2'),/Approval mismatch/);
await transition(3,'approve',payload,'h2');
await assert.rejects(transition(4,'publish',payload,'h1'),/Approval mismatch/);
await transition(4,'publish',payload,'h2');
await assert.rejects(transition(5,'publish',payload,'h2'),/immutable/);
await assert.rejects(transition(5,'revise',payload,'h2'),/immutable/);
assert.equal((await query('select count(*)::int as n from editorial_events')).rows[0].n,5);
assert.equal((await query('select count(*)::int as n from editorial_drafts')).rows[0].n,1);
assert.equal((await query('select editorial_claim($1,$2) as ok',[date,other])).rows[0].ok,false);
await query('set role anon');
await assert.rejects(query('select * from editorial_drafts'),/permission denied/);
await assert.rejects(query('select editorial_claim($1,$2)',[date,other]),/permission denied/);
await assert.rejects(query('select editorial_renew($1,$2)',[date,other]),/permission denied/);
await query('reset role');
await query('select editorial_claim($1,$2)', ['2026-09-08',attempt]);
await query("update editorial_runs set lease_until=now()-interval '1 second' where edition_date='2026-09-08'");
assert.equal((await query('select editorial_claim($1,$2) as ok',['2026-09-08',other])).rows[0].ok,true);
await assert.rejects(query('select editorial_finish($1,$2,$3,$4,$5)',['2026-09-08',attempt,null,null,{}]),/Lost run lease/);
await query('select editorial_finish($1,$2,$3,$4,$5)',['2026-09-08',other,null,null,{}]);
assert.equal((await query('select editorial_claim($1,$2) as ok',['2026-09-08',attempt])).rows[0].ok,true);
await db.close();
console.log('PASS: PostgreSQL migration, permissions, run lease fencing, retries, immutable revisions, approval and exactly-once publication');
